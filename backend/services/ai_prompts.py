# ============================================================
# DIFFICULTY
# ============================================================

def _difficulty_rules(difficulty: str) -> str:

    difficulty = (difficulty or "mixed").lower()

    if difficulty == "easy":
        return """
СЛОЖНОСТЬ: EASY

Проверяй базовое знание темы.

Характеристики:

- один основной факт;
- известное понятие;
- очевидная базовая связь;
- минимум рассуждений;
- понятная формулировка.

Easy должен быть доступен человеку, который знает основы темы.

Не используй редкие детали только ради сложности.
"""

    if difficulty == "medium":
        return """
СЛОЖНОСТЬ: MEDIUM

Проверяй уверенное знание темы.

Допустимо:

- связать два известных факта;
- сравнить близкие понятия;
- определить последствие события;
- применить известное правило;
- выбрать правильный вариант среди похожих.

Medium не должен решаться только по внешнему виду вариантов.
"""

    if difficulty == "hard":
        return """
СЛОЖНОСТЬ: HARD

Hard означает ГЛУБОКОЕ ПОНИМАНИЕ ТЕМЫ.

Главный принцип:

НЕ СПРАШИВАЙ ПРОСТО "ЗНАЕТ ЛИ ИГРОК ФАКТ".
СПРОСИ, ПОНИМАЕТ ЛИ ОН, КАК ФАКТ РАБОТАЕТ В КОНТЕКСТЕ.

Хороший hard:

- требует связать два или несколько фактов;
- проверяет причинно-следственную связь;
- требует сравнения похожих явлений;
- проверяет последствия события;
- требует отличить близкие понятия;
- требует применить знание к конкретной ситуации;
- проверяет важную, но не очевидную деталь;
- требует понимания контекста события.

Плохой hard:

- "Кто был X?"
- "В каком году произошло X?"
- "Как назывался X?"
- "Какой бог отвечал за X?"
- редкая дата;
- случайное имя;
- случайное число;
- второстепенная энциклопедическая мелочь.

ВАЖНО:

Если вопрос можно ответить одним фактом, который обычно знают из базового курса,
он НЕ должен считаться hard.

Например:

ПЛОХО:
"Как назывался бог мумификации в Древнем Египте?"

Это обычный факт.

ЛУЧШЕ:
"Почему культ Осириса оказался особенно важен для представлений египтян о загробной жизни?"

Если тип вопроса не позволяет дать длинный ответ, преобразуй эту идею
в короткую проверяемую задачу.

Для choice:

- варианты должны требовать различения близких концепций;
- правильный ответ не должен быть очевиден.

Для bool:

- утверждение должно проверять содержательную связь или последствие.

Для text:

- ответ должен быть коротким, но вопрос должен требовать понимания контекста.

Для matching:

- сопоставления должны быть содержательными, а не очевидными парами.

Для close:

- пропуски должны проверять связь нескольких фактов.

Для ordering:

- последовательность должна требовать знания реального развития событий.
"""

    return """
СЛОЖНОСТЬ: MIXED

Подбирай сложность естественно.

Easy:
- базовые факты;
- известные понятия.

Medium:
- связи;
- сравнения;
- применение.

Hard:
- глубокое понимание;
- последствия;
- причинность;
- различение близких явлений.

НЕ распределяй сложность механически только по позиции вопроса.

Каждый вопрос должен получить difficulty,
соответствующий его реальной интеллектуальной сложности.
"""


# ============================================================
# QUALITY
# ============================================================

def _quality_rules() -> str:

    return """
ОБЩИЕ ПРАВИЛА КАЧЕСТВА

1. ФАКТИЧЕСКАЯ КОРРЕКТНОСТЬ

Не придумывай:

- имена;
- даты;
- события;
- названия;
- цитаты;
- причинно-следственные связи.

Перед выдачей проверь правильный ответ.

2. ТЕМАТИЧЕСКАЯ КОРРЕКТНОСТЬ

Каждый вопрос должен действительно относиться к теме.

Не используй ложную предпосылку только ради интересного вопроса.

Например, если тема "Древний Рим",
плохой вопрос:

"Была ли битва при Гавгамелах победой римлян над парфянами?"

Это плохой вопрос даже при correct=false,
потому что Гавгамелы относятся к войнам Александра Македонского
против Персидской державы.

3. ОДНОЗНАЧНОСТЬ

У вопроса должен быть один объективный правильный ответ.

Если два ответа можно разумно защитить,
измени формулировку.

4. ИНТЕРЕСНОСТЬ

Не превращай квиз в энциклопедический экзамен.

Используй:

- сравнение;
- причинность;
- последствия;
- контекст;
- применение;
- узнавание;
- связи между фактами.

5. РАЗНООБРАЗИЕ

Не начинай все вопросы одинаково.

Не создавай подряд:

"Кто..."
"Кто..."
"Кто..."

Чередуй способы проверки знаний.

6. ПОВТОРЫ

Не спрашивай один и тот же факт дважды.

Не маскируй повтор изменением формулировки.

7. ПОДСКАЗКИ

Не раскрывай ответ в вопросе.

Для choice:

- правильный ответ не должен отличаться длиной;
- грамматика должна одинаково работать со всеми вариантами.

8. ЯЗЫК

Используй язык пользователя/темы.

Если тема на русском:

- используй нормальный русский;
- не смешивай кириллицу и латиницу внутри слов;
- не используй случайные диакритические знаки;
- не используй повреждённые слова.

НЕДОПУСТИМО:

"характеризováна"
"исторiя"
"Римскaя"

Допустимо только:

"характеризована"
"история"
"Римская"

Если сомневаешься в написании слова — используй общеупотребительную форму.

9. ИГРОВОЕ КАЧЕСТВО

Вопрос должен быть понятен человеку без необходимости разбирать
неестественную машинную формулировку.

10. ПОЖЕЛАНИЯ

Учитывай wishes, если они совместимы с:

- фактической корректностью;
- типом вопроса;
- сложностью;
- качеством игры.
"""


