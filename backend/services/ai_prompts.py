def generate_question_prompt(
    topic: str,
    question_type: str,
    difficulty: str,
    wishes: str = "",
    count: int = 3
) -> str:
    """
    Генерация вопросов одного типа.

    Промт специально сделан компактным:
    достаточно строгий для качества, но без лишнего расхода токенов.
    """

    type_rules = {
        "choice": """
CHOICE:
- ровно 4 варианта;
- только один правильный;
- "correct" — индекс правильного варианта (0-3);
- все варианты должны относиться к одной смысловой категории;
- неправильные варианты должны быть правдоподобными;
- правильный вариант не должен выделяться длиной или формулировкой.
Формат:
{"question":"...","options":["...","...","...","..."],"correct":0}
""",

        "bool": """
BOOL:
- содержательное утверждение;
- однозначно true или false;
- без двойного отрицания;
- ложное утверждение должно быть правдоподобным;
- не используй очевидные банальности.
Формат:
{"question":"...","correct":true}
""",

        "text": """
TEXT:
- открытый вопрос;
- ответ обычно 1-3 слова;
- ответ должен быть однозначным;
- не задавай вопрос с несколькими равноценными ответами.
Формат:
{"question":"...","correctAnswer":"..."}
""",

        "matching": """
MATCHING:
- ровно 3 пары;
- каждое соответствие однозначно;
- элементы должны быть связаны общей темой;
- не делай соответствия очевидными только по длине или грамматике.
Формат:
{"question":"...","pairs":[{"left":"...","right":"..."},{"left":"...","right":"..."},{"left":"...","right":"..."}]}
""",

        "close": """
CLOSE:
- используй ___ для пропусков;
- каждый пропуск должен иметь один короткий ответ;
- количество ответов должно совпадать с количеством пропусков;
- ответы в "correctAnswer" разделяй символом |.
Формат:
{"question":"... ___ ... ___ ...","correctAnswer":"ответ1|ответ2"}
""",

        "ordering": """
ORDERING:
- 3-5 элементов;
- порядок должен быть объективно определим;
- используй хронологию, этапы процесса, размер или другую понятную последовательность;
- "options" содержит элементы в ПРАВИЛЬНОМ порядке.
Формат:
{"question":"Расставьте элементы в правильном порядке:","options":["...","...","..."]}
"""
    }

    difficulty_rules = {
        "easy": """
EASY:
Базовый факт или простое применение знания.
Не используй редкий факт только ради сложности.
""",

        "medium": """
MEDIUM:
Нужно применить знание, сравнить факты, установить связь
или сделать один логический вывод.
""",

        "hard": """
HARD:
Нужно связать несколько фактов, сделать несколько шагов рассуждения,
различить близкие понятия или применить знание в новом контексте.
Сложность должна быть интеллектуальной, а не просто основанной
на редкости факта.
""",

        "very_easy": """
VERY EASY:
Самый базовый факт, термин, объект или очевидное соответствие.
""",

        "very_hard": """
VERY HARD:
Глубокое понимание темы, несколько связанных шагов рассуждения
или тонкое различение близких понятий.
Не используй случайные obscure-факты ради сложности.
"""
    }

    type_rule = type_rules.get(question_type, type_rules["choice"])
    difficulty_rule = difficulty_rules.get(
        difficulty.lower(),
        f"Уровень сложности: {difficulty}."
    )

    wishes_text = wishes.strip() if wishes and wishes.strip() else "нет"

    return f"""
Ты — профессиональный автор качественных интеллектуальных викторин.

ТЕМА:
{topic}

ТИП:
{question_type}

{type_rule}

СЛОЖНОСТЬ:
{difficulty_rule}

КОЛИЧЕСТВО:
{count}

ПОЖЕЛАНИЯ:
{wishes_text}

ГЛАВНЫЕ ПРАВИЛА:

1. Каждый вопрос должен проверять КОНКРЕТНОЕ знание, связь между
знаниями или применение знания.

2. Вопрос должен иметь однозначный ответ.

3. Не придумывай факты.

4. Не создавай несколько вопросов, проверяющих одно и то же знание.
Например:
"Кто основал Рим?"
"Кем был основан Рим?"
"Назовите основателя Рима?"
— это один вопрос, а не три.

5. Не используй формулировку, из которой можно угадать ответ.

6. Не делай сложность искусственной.
HARD ≠ редкий факт.

7. Не используй субъективные вопросы, если нет объективного критерия.

8. Формулировка должна быть естественной и интересной.

9. Если пользовательские пожелания противоречат этим правилам
или делают вопрос некорректным, сохрани качество вопроса.

ПЕРЕД ВОЗВРАТОМ:
Внутренне проверь каждый вопрос:
- соответствует теме;
- соответствует сложности;
- имеет один правильный ответ;
- фактически корректен;
- не повторяет другие вопросы;
- не содержит подсказки;
- соответствует своему типу.

Если вопрос не проходит проверку — исправь его.

ОТВЕТ:
Верни ТОЛЬКО валидный JSON-массив.
Без Markdown, без ```json и без пояснений.

Пример:
[
    {{
        "question": "..."
    }}
]
"""


def improve_question_prompt(
    current_text: str,
    format_type: str,
    topic: str = "",
    wishes: str = ""
) -> str:
    """
    Улучшение существующего вопроса.
    """

    topic_text = topic.strip() if topic and topic.strip() else "не указана"
    wishes_text = wishes.strip() if wishes and wishes.strip() else "нет"

    return f"""
Ты — профессиональный редактор вопросов для викторин.

ИСХОДНЫЙ ВОПРОС:
{current_text}

ТИП:
{format_type}

ТЕМА:
{topic_text}

ПОЖЕЛАНИЯ:
{wishes_text}

Создай 3 улучшенные версии одного и того же вопроса:

- easy
- medium
- hard

Все версии должны проверять ОДНО И ТО ЖЕ ОСНОВНОЕ ЗНАНИЕ.
Меняй глубину и способ проверки, но не меняй смысл.

EASY:
Прямая проверка базового знания.

MEDIUM:
Применение знания, сравнение или один логический шаг.

HARD:
Более глубокое понимание, несколько связанных шагов
или различение близких понятий.

Не делай hard сложным просто из-за редкого факта.

Каждая версия должна:
- быть однозначной;
- быть фактически корректной;
- соответствовать типу;
- не иметь лишних подсказок;
- не допускать несколько правильных ответов;
- звучать естественно.

Если исходный вопрос плохой, исправь его,
сохранив тему и основное проверяемое знание.

Верни ТОЛЬКО JSON:

{{
    "variants": [
        {{
            "difficulty": "easy",
            "question": "..."
        }},
        {{
            "difficulty": "medium",
            "question": "..."
        }},
        {{
            "difficulty": "hard",
            "question": "..."
        }}
    ]
}}
"""


def generate_quiz_prompt(
    topic: str,
    count: int = 10,
    wishes: str = ""
) -> str:
    """
    Генерация полноценного квиза.

    Промт оптимизирован для одного API-запроса:
    модель получает всю задачу сразу и генерирует вопросы одним ответом.
    """

    wishes_text = wishes.strip() if wishes and wishes.strip() else "нет"

    return f"""
Ты — профессиональный автор интеллектуальных викторин.

Создай квиз по теме:
{topic}

Количество вопросов:
{count}

Пожелания:
{wishes_text}

РАСПРЕДЕЛЕНИЕ:

Примерно:
- 60% choice
- 20% text
- 10% bool
- 10% matching

Для маленького количества вопросов допускается округление.
Итоговое количество вопросов должно быть ровно {count}.

СЛОЖНОСТЬ:

Примерно:
- 20-30% easy
- 40-50% medium
- 20-30% hard

Не нужно соблюдать проценты математически точно для маленького квиза.

ГЛАВНЫЙ ПРИНЦИП:

Каждый вопрос должен проверять отдельное конкретное знание.

Не создавай несколько вариантов одного вопроса:

ПЛОХО:
"Кто написал X?"
"Автором X был кто?"
"Кто является автором X?"

Это один knowledge target.

ХОРОШО:
Каждый вопрос проверяет другую информацию, связь,
сравнение, причину, следствие, последовательность,
применение или другой аспект темы.

РАЗНООБРАЗИЕ:

Используй разные способы проверки:
- факт;
- сравнение;
- причина → следствие;
- следствие → причина;
- классификация;
- хронология;
- применение;
- отличие похожих понятий;
- пример;
- связь между объектами.

Не повторяй одну конструкцию много раз.

QUALITY CHECK:

Перед возвратом внутренне проверь каждый вопрос:

1. Он относится к теме.
2. Он проверяет отдельное знание.
3. Есть один однозначный правильный ответ.
4. Факт корректен.
5. Сложность соответствует уровню.
6. Нет подсказки в формулировке.
7. Нет повторения другого вопроса.
8. Тип вопроса соблюдён.
9. Вопрос интересен, а не создан только ради количества.

Если вопрос не проходит проверку — перепиши его.

CHOICE:

- ровно 4 варианта;
- только один правильный;
- correct — индекс 0-3;
- неправильные варианты правдоподобны;
- все варианты одной смысловой категории;
- правильный вариант не должен выделяться длиной.

TEXT:

- короткий однозначный ответ;
- обычно 1-3 слова;
- не допускай нескольких равноценных ответов.

BOOL:

- содержательное утверждение;
- однозначно true/false;
- без двойного отрицания;
- не используй банальные утверждения.

MATCHING:

- ровно 3 пары;
- однозначные соответствия;
- пары должны проверять реальные знания.

Не придумывай факты.
Не используй случайные редкие факты только для hard.
Не используй субъективные вопросы без объективного ответа.

ФОРМАТ:

Верни ТОЛЬКО валидный JSON.
Без Markdown.
Без ```json.
Без пояснений.

{{
    "title": "Название квиза",
    "questions": [
        {{
            "type": "choice",
            "question": "...",
            "options": ["...", "...", "...", "..."],
            "correct": 0
        }},
        {{
            "type": "text",
            "question": "...",
            "correctAnswer": "..."
        }},
        {{
            "type": "bool",
            "question": "...",
            "correct": true
        }},
        {{
            "type": "matching",
            "question": "Сопоставьте:",
            "pairs": [
                {{"left": "...", "right": "..."}},
                {{"left": "...", "right": "..."}},
                {{"left": "...", "right": "..."}}
            ]
        }}
    ]
}}
"""


def generate_jeopardy_categories_prompt(
    topic: str,
    wishes: str = ""
) -> str:
    """
    Генерация категорий Jeopardy.
    """

    wishes_text = wishes.strip() if wishes and wishes.strip() else "нет"

    return f"""
Ты — профессиональный автор игры «Своя игра» (Jeopardy).

ТЕМА:
{topic}

Нужно создать 3 категории.

ПОЖЕЛАНИЯ:
{wishes_text}

Категории должны:

- охватывать разные аспекты темы;
- не дублировать друг друга;
- иметь понятные и привлекательные названия;
- быть достаточно широкими для вопросов от 100 до 500 очков;
- позволять постепенно повышать сложность.

ПЛОХО:
- История темы
- Исторические события темы
- Исторические факты темы

Это практически одна категория.

ХОРОШО:
Разные области, например:
- Персоналии
- События
- Культура

Но конкретные категории должны соответствовать самой теме.

description:
Одна короткая фраза о содержании категории.

Верни ТОЛЬКО JSON:

{{
    "categories": [
        {{
            "name": "...",
            "description": "..."
        }},
        {{
            "name": "...",
            "description": "..."
        }},
        {{
            "name": "...",
            "description": "..."
        }}
    ]
}}

Без Markdown и пояснений.
"""


def generate_jeopardy_questions_prompt(
    category: str,
    empty_slots: list[int],
    wishes: str = ""
) -> str:
    """
    Генерация вопросов для конкретной категории Jeopardy.
    """

    difficulty_map = {
        100: "очень лёгкий",
        200: "лёгкий",
        300: "средний",
        400: "сложный",
        500: "очень сложный",
    }

    slots_desc = "\n".join(
        f"- {slot}: {difficulty_map.get(slot, 'средний')}"
        for slot in empty_slots
    )

    wishes_text = wishes.strip() if wishes and wishes.strip() else "нет"

    return f"""
Ты — профессиональный автор вопросов для игры «Своя игра» (Jeopardy).

КАТЕГОРИЯ:
{category}

СОЗДАЙ ВОПРОСЫ ДЛЯ:
{slots_desc}

ПОЖЕЛАНИЯ:
{wishes_text}

ФОРМАТ JEOPARDY:

Игрок получает формулировку-подсказку и должен назвать ответ.

Не используй варианты ответа.
Не задавай вопросы, на которые можно ответить только "да/нет".
Каждый вопрос должен иметь один короткий однозначный ответ.

СЛОЖНОСТЬ:

100:
Базовый, хорошо известный факт категории.

200:
Конкретный факт, который требует знания темы.

300:
Хорошее знание темы или простая связь между фактами.

400:
Сложный вопрос, требующий сравнения, контекста,
нескольких связанных фактов или менее очевидного знания.

500:
Самый сложный вопрос категории.
Требует глубокого знания или нескольких шагов рассуждения.

ВАЖНО:
500 не означает "самый редкий факт".
Не используй obscure-факт только ради высокой стоимости.

РАЗНООБРАЗИЕ:

Каждая стоимость должна проверять ДРУГОЕ знание.

Не делай пять вопросов об одном человеке,
одном событии или одном факте.

КАЧЕСТВО:

Каждый вопрос должен:
- соответствовать категории;
- иметь один правильный ответ;
- быть фактически корректным;
- соответствовать своей стоимости;
- быть интересным;
- не содержать подсказку к ответу;
- не зависеть от мнения;
- не повторять другой вопрос.

ПЕРЕД ОТВЕТОМ:

Внутренне проверь каждый вопрос.
Если ответ неоднозначен или вопрос слишком лёгкий/сложный
для своей стоимости — исправь его.

Верни ТОЛЬКО JSON:

{{
    "questions": [
        {{
            "points": 100,
            "q": "текст вопроса",
            "a": "правильный ответ"
        }}
    ]
}}

Добавь только запрошенные стоимости.

Без Markdown.
Без ```json.
Без пояснений.
"""
