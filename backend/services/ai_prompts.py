# ============================================================
# DIFFICULTY
# ============================================================

def _difficulty_rules(difficulty: str) -> str:
    difficulty = (difficulty or "mixed").lower()

    if difficulty == "easy":
        return """
СЛОЖНОСТЬ: EASY.

Проверяй базовое знание темы.
- Один известный факт или простая связь.
- Не требуй длинной цепочки рассуждений.
- Не используй редкие детали только ради сложности.
- Формулировка должна быть ясной.
"""

    if difficulty == "medium":
        return """
СЛОЖНОСТЬ: MEDIUM.

Проверяй уверенное знание темы.
- Допустимо связать два факта.
- Допустимо простое применение знания.
- Неправильные ответы должны быть правдоподобными.
- Вопрос не должен решаться только по форме вариантов.
"""

    if difficulty == "hard":
        return """
СЛОЖНОСТЬ: HARD.

Проверяй глубокое понимание темы.

Hard НЕ означает "случайный редкий факт".

Предпочитай:
- причинно-следственные связи;
- сравнение близких явлений;
- применение знания;
- связь нескольких фактов;
- понимание последствий события;
- различение похожих понятий;
- менее очевидные, но важные детали темы.

Избегай:
- бессмысленных дат и чисел;
- случайных имён;
- энциклопедической мелочёвки;
- вопросов, где сложность возникает только из-за незнакомого слова;
- запутанной формулировки.

Если вопрос можно решить простым запоминанием одного общеизвестного факта,
он скорее всего НЕ является hard.
"""

    return """
СЛОЖНОСТЬ: MIXED.

Распределяй сложность естественно:
- начало — преимущественно easy;
- середина — medium;
- конец — medium/hard.

Не делай все вопросы одинаковыми.
difficulty должен соответствовать реальной сложности каждого вопроса.
"""


# ============================================================
# QUALITY RULES
# ============================================================

def _quality_rules() -> str:
    return """
ОБЩИЕ ПРАВИЛА КАЧЕСТВА:

1. ТЕМА
Каждый вопрос должен непосредственно относиться к указанной теме.

2. ФАКТИЧЕСКАЯ КОРРЕКТНОСТЬ
Не придумывай факты, имена, даты, названия или статистику.
Перед выдачей проверь правильный ответ.

3. ТЕМАТИЧЕСКАЯ ЦЕЛОСТНОСТЬ
Не используй вопросы, построенные на ложной предпосылке.

Например, если тема — Древний Рим, нельзя спрашивать:
"Была ли битва при Гавгамелах победой римлян над парфянами?"
Даже если ответ false, сам вопрос плохой, потому что Гавгамелы относятся
к войнам Александра Македонского против Персидской державы.

4. ОДНОЗНАЧНОСТЬ
У вопроса должен быть один объективно правильный ответ.
Если два ответа можно разумно считать правильными — переделай вопрос.

5. ИНТЕРЕСНОСТЬ
Не превращай квиз в список сухих энциклопедических фактов.
Используй факты, сравнение, узнавание, связи, последствия и применение.

6. РАЗНООБРАЗИЕ
Не начинай подряд вопросы одинаково.
Чередуй конструкции и способы проверки знаний.

7. ПОВТОРЫ
Не повторяй один факт или одну мысль в разных вопросах.

8. ПОДСКАЗКИ
Не вставляй правильный ответ в формулировку вопроса.
Не делай правильный вариант очевидным по длине или грамматике.

9. ЯЗЫК
Используй один естественный язык на протяжении всего вопроса.

Если тема/запрос на русском:
- используй русский язык;
- не вставляй случайные латинские буквы внутрь русских слов;
- не используй случайные диакритические знаки;
- не смешивай кириллицу и латиницу внутри слов.

НЕЛЬЗЯ получать повреждённые слова вроде:
"характеризováна"
"исторiя"
"Римскaя"

Если слово выглядит повреждённым — перепиши его полностью.

10. ИГРОВОЕ КАЧЕСТВО
Вопрос должен быть интересен человеку, который реально играет.
Не усложняй вопрос плохой формулировкой.

11. ПОЖЕЛАНИЯ
Учитывай wishes, если они совместимы с корректностью и форматом.
"""


