def _final_check() -> str:

    return """
ФИНАЛЬНАЯ ПРОВЕРКА

Перед выдачей JSON проверь каждый вопрос:

1. Он относится к теме?
2. Его предпосылка фактически корректна?
3. Правильный ответ действительно правильный?
4. Есть только один правильный ответ?
5. Тип соответствует содержимому?
6. Формат соответствует контракту?
7. Difficulty соответствует реальной сложности?
8. Hard действительно требует понимания, а не редкого факта?
9. Нет повторения другого вопроса?
10. Нет подсказки в формулировке?
11. Нет искусственной или кривой формулировки?
12. Нет смешения языков?
13. Нет повреждённых слов?
14. Нет случайных латинских букв или диакритики?
15. Вопрос интересен для игры?

Если хотя бы один ответ "нет" —
исправь вопрос ДО выдачи результата.

Не объясняй исправления.
"""


