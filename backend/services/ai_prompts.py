def generate_question_prompt(
    topic: str,
    question_type: str,
    difficulty: str,
    wishes: str = "",
    count: int = 3,
) -> str:

    question_type = question_type or "choice"

    type_rules = TYPE_RULES.get(
        question_type,
        TYPE_RULES["choice"],
    )

    return f"""
Ты — профессиональный автор интеллектуальных викторин.

Создай {count} независимых вариантов вопроса по теме:
«{topic}»

Тип:
{question_type}

{type_rules}

{_difficulty_rules(difficulty)}

{_quality_rules()}

Пожелания пользователя:
{wishes.strip() if wishes and wishes.strip() else "Нет дополнительных пожеланий."}

ТРЕБОВАНИЯ:

- Каждый вариант — самостоятельный вопрос.
- Не перефразируй один вопрос несколько раз.
- Варианты должны отличаться содержанием.
- Каждый объект обязан содержать difficulty.
- Не добавляй лишние поля.

{_final_check()}

ФОРМАТ:

[
  {{
    "type": "{question_type}",
    "difficulty": "easy|medium|hard",
    ...
  }}
]

{_json_rules()}
""".strip()


