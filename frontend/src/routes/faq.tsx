function FAQPage() {
  const [search, setSearch] = useState("");
  const [expanded, setExpanded] = useState<string | null>(null);

  const filtered = faqData.map(cat => ({
    ...cat,
    items: cat.items.filter(
      item =>
        !search ||
        item.q.toLowerCase().includes(search.toLowerCase()) ||
        item.a.toLowerCase().includes(search.toLowerCase())
    ),
  })).filter(cat => cat.items.length > 0);

  return (
    <div className="min-h-screen bg-surface">
      <SiteHeader />
      <main className="mx-auto max-w-3xl px-4 py-8 sm:px-6 sm:py-12">
        <h1 className="font-display text-3xl font-black tracking-tight sm:text-4xl">FAQ</h1>
        <p className="mt-2 text-sm leading-relaxed text-muted-foreground sm:text-base">
          Ответы на частые вопросы. Не нашли ответ?{" "}
          <Link to="/feedback" className="text-primary hover:underline font-semibold">
            Напишите нам
          </Link>.
        </p>

        <div className="relative mt-6">
          <Search className="absolute left-3 top-1/2 h-4 w-4 -translate-y-1/2 text-muted-foreground" />
          <input
            value={search}
            onChange={(e) => setSearch(e.target.value)}
            placeholder="Поиск по вопросам..."
            className="input-base pl-10"
          />
        </div>

        <div className="mt-8 space-y-8">
          {filtered.map(cat => (
            <div key={cat.category}>
              <h2 className="font-display text-xl font-bold mb-3">{cat.category}</h2>
              <div className="space-y-2">
                {cat.items.map(item => {
                  const isOpen = expanded === `${cat.category}-${item.q}`;
                  return (
                    <div key={item.q} className="surface-card overflow-hidden">
                      <button
                        onClick={() => setExpanded(isOpen ? null : `${cat.category}-${item.q}`)}
                        className="flex w-full items-center justify-between gap-3 px-4 py-4 text-left font-semibold hover:bg-surface-muted/50 sm:px-5"
                      >
                        <span className="flex items-center gap-2">
                          <HelpCircle className="h-4 w-4 shrink-0 text-primary" />
                          <span className="min-w-0 break-words">{item.q}</span>
                        </span>
                        <ChevronDown className={`h-4 w-4 shrink-0 transition-transform ${isOpen ? "rotate-180" : ""}`} />
                      </button>
                      {isOpen && (
                        <div className="break-words px-4 pb-4 text-sm leading-relaxed text-muted-foreground sm:px-5">
                          {item.a}
                        </div>
                      )}
                    </div>
                  );
                })}
              </div>
            </div>
          ))}
        </div>

        {filtered.length === 0 && (
          <div className="surface-card p-12 text-center text-muted-foreground">
            <Search className="mx-auto mb-3 h-8 w-8 opacity-40" />
            <p>Ничего не найдено по запросу «{search}»</p>
          </div>
        )}

        <div className="surface-card mt-12 p-8 text-center">
          <h2 className="font-display text-xl font-bold">Не нашли ответ?</h2>
          <p className="mt-2 text-muted-foreground">
            Напишите нам через форму обратной связи — мы ответим лично.
          </p>
          <Link to="/feedback" className="btn-accent mt-4 inline-flex">
            Написать нам
          </Link>
        </div>
      </main>
    </div>
  );
}
